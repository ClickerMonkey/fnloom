/**
 * Writes the web app's ayepi manifest (`packages/web/src/api/manifest.gen.ts`) from `hubWebSpec`, so the browser gets
 * the zod-free description of the web API. With `--check` it fails when the file is stale instead of writing it, so
 * a spec change breaks `npm run check` until the manifest matches.
 *
 * Run: npm run web:manifest   (check: npm run web:manifest -- --check)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { manifestFromSpec } from '@ayepi/core';
import { hubWebSpec } from '@harness/core';

const target = fileURLToPath(new URL('../packages/web/src/api/manifest.gen.ts', import.meta.url));
const body = JSON.stringify(manifestFromSpec(hubWebSpec), null, 2);
const text = `// Generated by scripts/web-manifest.ts from hubWebSpec. Do not edit; run \`npm run web:manifest\`.\nimport type { Manifest } from '@ayepi/core/client';\n\nexport const manifest = ${body} as const satisfies Manifest;\n`;

const check = process.argv.includes('--check');
const read = (): string => { try { return readFileSync(target, 'utf8'); } catch { return ''; } };
const current = read();
if (check) {
  if (current !== text) {
    console.error('web.manifest.stale', { file: target, fix: 'npm run web:manifest' });
    process.exit(1);
  }
} else if (current !== text) {
  writeFileSync(target, text);
  console.info('web.manifest.written', { file: target });
}
