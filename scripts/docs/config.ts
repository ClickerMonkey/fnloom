/**
 * The authoring guide's real config: the SDK's public entry points, core as the package whose types the reference
 * reaches, the gin builder, and the generators (template and example files verbatim, the fs contract, the hub contract
 * read from the SDK, the `system.json` schema from core, the mistakes from the SDK's compile-time tests).
 */
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { SystemPackageManifest } from '@harness/core';
import { hub } from '@harness/sdk';
import { z } from 'zod';
import { COMMANDS, usageOf } from '../../packages/cli/src/index.ts';
import { fence, renderReached, table } from './compose.ts';
import { contractListing } from './contract-listing.ts';
import { filesUnder, folderListing, readText, type GuideConfig } from './guide.ts';
import { mistakesIn, renderMistakes } from './mistakes.ts';
import { GIN_EXTERNALS, OUTLINE } from './outline.ts';

const ROOT = fileURLToPath(new URL('../..', import.meta.url));
/** Where the guide is written. */
export const AUTHORING_FILE = join(ROOT, 'packages/sdk/AUTHORING.md');
const TYPETESTS = 'packages/sdk/typetests';

const at = (path: string): string => join(ROOT, path);

/** The guide's config: the SDK's public entry points, core as the reached package, and the real generators. */
export const AUTHORING_CONFIG: GuideConfig = {
  root: ROOT,
  title: 'Writing a harness system',
  intro: [
    'Everything needed to write a harness system, in one file: how a system is laid out, every builder, type, ref and',
    'helper of `@harness/sdk` with its TSDoc and signature, the run context, renderers, packaging, testing, the mistakes',
    'the compiler refuses, and complete compiled examples. An LLM writing a system needs only this file.',
    '',
    '_Generated by `scripts/docs/authoring.ts` from the SDK\'s sources (`npm run docs:authoring`); do not edit it by hand._',
    '_Every code sample is a compiled file of the repository, so it is correct for this version of the SDK._',
  ].join('\n'),
  entries: [
    { specifier: '@harness/sdk', file: at('packages/sdk/src/index.ts') },
    { specifier: '@harness/sdk/server', file: at('packages/sdk/src/server/index.ts') },
    { specifier: '@harness/sdk/server/testing', file: at('packages/sdk/src/server/testing.ts') },
    { specifier: '@harness/sdk/build', file: at('packages/sdk/src/build.ts') },
  ],
  external: [{ specifier: '@aeye/gin', from: at('packages/sdk/src/gin.ts'), names: GIN_EXTERNALS }],
  reach: (file) => file.includes('/packages/core/src/'),
  reachDepth: 1,
  outline: OUTLINE,
  proseDir: fileURLToPath(new URL('prose', import.meta.url)),
  generators: (api) => ({
    'template-files': () => folderListing(ROOT, 'systems/template'),
    'example-system': () => folderListing(ROOT, 'scripts/docs/example'),
    'fs-contract': () => fence(readText(at('systems/fs/shared/index.ts')) ?? '', 'ts'),
    'hub-contract': () => contractListing(hub),
    'cli-commands': () => table(['Command', 'What it does'], COMMANDS.map((c) => [`\`${usageOf(c)}\``, c.summary])),
    'system-json-schema': () => fence(JSON.stringify(z.toJSONSchema(SystemPackageManifest, { io: 'input' }), null, 2), 'json'),
    mistakes: () => renderMistakes(filesUnder(at(TYPETESTS)).filter((f) => f.endsWith('.ts')).flatMap((f) => mistakesIn(readText(at(`${TYPETESTS}/${f}`)) ?? '', `${TYPETESTS}/${f}`))),
    'core-types': () => renderReached(api),
  }),
};
