/**
 * Writes the authoring guide as fs's context folder (`systems/fs/context/authoring/`): markdown files, each a YAML
 * header (`ContextFileHeader` from `@harness/core`) and then its content. The index (`fs/authoring`) offers the topic
 * groups as choices; each group offers its parts; each part offers its API reference (when it has one) and the part
 * after it. Every item but a reference brings the fns an author writes with, and the body names them as `fn:` links,
 * so the build checks them. Links that worked in the single file are made to work across items (`context-links.ts`).
 * A part (or reference) over the item budget is cut into pieces under it (`split.ts`), each offered as a choice.
 * The words are in `context-graph.ts`; the text is the guide's own, so the folder is never edited by hand.
 */
import { ContextFileHeader, type ContextChoice, type QualifiedName } from '@harness/core';
import { AUTHORING_GROUPS, AUTHORING_INDEX, PART_WORDS, type AuthoringGroup } from './context-graph.ts';
import { anchorHomes, linkItem, sectionTitles } from './context-links.ts';
import type { GuidePart } from './parts.ts';
import { cutPart, pieceSlug, type EachSection, type Piece } from './split.ts';

/** The system that serves the folder. */
const SYSTEM = 'fs';

/** Where the folder is, from the repository root. */
export const AUTHORING_CONTEXT_DIR = 'systems/fs/context/authoring';

/** The fns an author writes a system with, brought by every item but a reference. */
const AUTHOR_FNS = ['fs/read', 'fs/write', 'fs/edit', 'fs/bash'] as const;

/** What packaging and the index bring besides: installing from the chat. */
const INSTALL_FNS = ['fs/install_system', 'fs/system_status'] as const;

/** The longest summary an item has: one short line a small model reads in a list of choices. */
const SUMMARY_MAX = 160;

/** Where the API reference of a part starts (`compose.ts` writes it under this heading). */
const REFERENCE_HEADING = '\n### Reference: ';

/** One file of the folder: its path under the folder and its text. */
export interface ContextFile {
  readonly path: string;
  readonly text: string;
}

const qualified = (key: string): QualifiedName => `${SYSTEM}/${key}`;
const partKey = (topic: string): string => `authoring.${topic}`;
const groupKey = (group: AuthoringGroup): string => `authoring.topics.${group.id}`;

/** A header as YAML: every scalar JSON-quoted (valid YAML), lists of names in flow style, choices as a block list. */
function yaml(header: ContextFileHeader): string {
  const lines = ['---', '# Generated by scripts/docs/authoring.ts from the authoring guide (npm run docs:authoring); do not edit.'];
  const scalar = (name: string, value: string | undefined) => { if (value !== undefined) { lines.push(`${name}: ${JSON.stringify(value)}`); } };
  const names = (name: string, values: readonly string[]) => { if (values.length > 0) { lines.push(`${name}: [${values.map((value) => JSON.stringify(value)).join(', ')}]`); } };
  scalar('key', header.key);
  scalar('title', header.title);
  scalar('description', header.description);
  scalar('summary', header.summary);
  scalar('parent', header.parent);
  scalar('next', header.next);
  names('fns', header.fns);
  names('imports', header.imports);
  if (header.suggest !== 'both') { scalar('suggest', header.suggest); }
  names('tags', header.tags);
  if (header.choices !== undefined && header.choices.length > 0) {
    lines.push('choices:');
    for (const choice of header.choices) { lines.push(`  - to: ${JSON.stringify(choice.to)}`, `    when: ${JSON.stringify(choice.when)}`); }
  }
  lines.push('---');
  return lines.join('\n');
}

/** A file before its links are made: its path, its header and its body. */
interface Draft {
  readonly path: string;
  readonly header: ContextFileHeader;
  readonly body: string;
}

/** A file from its header (checked against the schema, so the generator can't write a header the build refuses). */
function file(path: string, header: Partial<ContextFileHeader> & Pick<ContextFileHeader, 'key' | 'description' | 'summary'>, body: string): Draft {
  return { path, header: ContextFileHeader.parse(header), body };
}

/** The drafts as files, each body's anchors and section titles linked across the folder. */
function linked(drafts: readonly Draft[], parts: readonly GuidePart[]): ContextFile[] {
  const items = drafts.map((draft) => ({ key: qualified(draft.header.key), body: draft.body }));
  const homes = anchorHomes(items);
  const titles = sectionTitles(parts.map((part) => ({ key: qualified(partKey(part.topic.id)), title: part.topic.title })));
  return items.map((item, index) => {
    const draft = drafts[index];
    if (draft === undefined) { throw new Error('a draft for every item'); }
    return { path: draft.path, text: `${yaml(draft.header)}\n\n${linkItem(item, homes, titles).trim()}\n` };
  });
}

/** A part's prose and its API reference, cut at the reference heading. */
function split(part: GuidePart): { prose: string; reference: string | undefined } {
  if (part.topic.reference === true) { return { prose: part.text, reference: undefined }; }
  const at = part.text.indexOf(REFERENCE_HEADING);
  return at < 0 ? { prose: part.text, reference: undefined } : { prose: part.text.slice(0, at), reference: part.text.slice(at + 1) };
}

/** The fns an item brings: none for a reference; the install fns too where installing is the subject. */
function fnsOf(install: boolean): QualifiedName[] {
  return [...AUTHOR_FNS, ...(install ? INSTALL_FNS : [])];
}

/** The line every item that brings fns ends with, naming them as `fn:` links the build checks. */
function fnsLine(fns: readonly string[]): string {
  return `Fns for this: ${fns.map((name) => `fn:${name}`).join(', ')}.`;
}

/** The folder's files, in a stable order: the index, the groups, then each part and its reference. */
export function contextFiles(parts: readonly GuidePart[]): ContextFile[] {
  const byTopic = new Map(parts.map((part) => [part.topic.id, part]));
  const groupOf = new Map(AUTHORING_GROUPS.flatMap((group) => group.topics.map((topic) => [topic, group] as const)));
  const placed = new Set(groupOf.keys());
  const missing = parts.filter((part) => !placed.has(part.topic.id)).map((part) => part.topic.id);
  if (missing.length > 0) { throw new Error(`context-graph.ts places no group for the topics ${missing.join(', ')}`); }
  const wordsOf = (topic: string) => {
    const words = PART_WORDS[topic];
    if (words === undefined) { throw new Error(`context-graph.ts has no words for the topic ${topic}`); }
    return words;
  };

  const indexFns = fnsOf(true);
  const files: Draft[] = [file('index.md', {
    key: AUTHORING_INDEX.key,
    title: AUTHORING_INDEX.title,
    description: AUTHORING_INDEX.summary,
    summary: AUTHORING_INDEX.summary,
    fns: indexFns,
    tags: ['authoring'],
    choices: AUTHORING_GROUPS.map((group) => ({ to: qualified(groupKey(group)), when: group.when })),
  }, AUTHORING_INDEX.body)];

  for (const group of AUTHORING_GROUPS) {
    const install = group.topics.includes('packaging');
    const lines = group.topics.flatMap((topic) => {
      const part = byTopic.get(topic);
      return part === undefined ? [] : [`- [${part.topic.title}](context:${qualified(partKey(topic))}): ${wordsOf(topic).summary}`];
    });
    files.push(file(`topics/${group.id}.md`, {
      key: groupKey(group),
      title: group.title,
      description: group.summary,
      summary: group.summary,
      parent: qualified(AUTHORING_INDEX.key),
      fns: fnsOf(install),
      tags: ['authoring'],
      choices: group.topics.flatMap((topic) => (byTopic.has(topic) ? [{ to: qualified(partKey(topic)), when: wordsOf(topic).when }] : [])),
    }, [`# ${group.title}`, '', group.summary, '', ...lines, '', fnsLine(fnsOf(install))].join('\n')));
  }

  parts.forEach((part, index) => {
    const topic = part.topic.id;
    const words = wordsOf(topic);
    const group = groupOf.get(topic);
    const { prose, reference } = split(part);
    const after = parts[index + 1];
    const next = after !== undefined && (after.topic.reference === true) === (part.topic.reference === true) ? after : undefined;
    const isReference = part.topic.reference === true;
    const install = topic === 'packaging';
    const fns = isReference ? [] : fnsOf(install);
    const proseCut = pieces({ key: partKey(topic), path: `parts/${topic}`, title: part.topic.title, text: prose, fns, reference: isReference, each: part.topic.each });
    const choices = [
      ...proseCut.choices,
      ...(reference === undefined ? [] : [{ to: qualified(`${partKey(topic)}.reference`), when: 'Pick this when you need the exact signatures and options.' }]),
      ...(next === undefined ? [] : [{ to: qualified(partKey(next.topic.id)), when: `Pick this to go on in order: ${next.topic.title}.` }]),
    ];
    files.push(file(`parts/${topic}.md`, {
      key: partKey(topic),
      title: part.topic.title,
      description: `Writing a harness system: ${part.topic.title}.`,
      summary: words.summary,
      ...(group === undefined ? {} : { parent: qualified(groupKey(group)) }),
      ...(next === undefined ? {} : { next: qualified(partKey(next.topic.id)) }),
      fns,
      ...(isReference ? { suggest: 'none' as const, tags: ['authoring', 'reference'] } : { tags: ['authoring'] }),
      choices,
    }, fns.length === 0 ? proseCut.body : `${proseCut.body.trim()}\n\n${fnsLine(fns)}`));
    files.push(...proseCut.drafts);
    if (reference !== undefined) {
      const title = `${part.topic.title}: reference`;
      const referenceCut = pieces({ key: `${partKey(topic)}.reference`, path: `parts/${topic}.reference`, title, text: reference, fns: [], reference: true, each: undefined });
      files.push(file(`parts/${topic}.reference.md`, {
        key: `${partKey(topic)}.reference`,
        title,
        description: `The API reference of ${part.topic.title}: every export with its TSDoc and signature.`,
        summary: `Signatures and options for ${part.topic.title.toLowerCase()}.`,
        parent: qualified(partKey(topic)),
        suggest: 'none',
        tags: ['authoring', 'reference'],
        ...(referenceCut.choices.length === 0 ? {} : { choices: referenceCut.choices }),
      }, referenceCut.body));
      files.push(...referenceCut.drafts);
    }
  });
  return linked(files, parts);
}

/** What `pieces` cuts: an item's key, path (without `.md`), title and text, the fns it brings, and how to cut it. */
interface PieceSource {
  readonly key: string;
  readonly path: string;
  readonly title: string;
  readonly text: string;
  readonly fns: readonly QualifiedName[];
  readonly reference: boolean;
  readonly each: EachSection | undefined;
}

/** Text cut to fit a choice line or a summary: whole when short enough, else cut at a word with an ellipsis. */
function fit(text: string, max: number): string {
  if (text.length <= max) { return text; }
  const cut = text.slice(0, max - 1);
  return `${cut.slice(0, Math.max(cut.lastIndexOf(' '), max / 2))}…`;
}

/**
 * An item over the budget, cut (`split.ts`): its own body keeps the text before its first section and lists the
 * pieces as links, its choices offer each piece, and each piece is an item under it (`<key>.<slug>`, in a folder named
 * after it), linked to the next. An item that fits comes back as it was, with no pieces.
 */
function pieces(source: PieceSource): { body: string; choices: ContextChoice[]; drafts: Draft[] } {
  const cut = cutPart(source.text, source.each === undefined ? {} : { each: source.each });
  if (cut === undefined) { return { body: source.text, choices: [], drafts: [] }; }
  const used = new Set<string>();
  const keyed = cut.pieces.map((piece) => {
    // named by its first section, so a piece of a cut section isn't named after its parent
    const base = pieceSlug(piece.names[0] ?? piece.title);
    let slug = base;
    for (let n = 2; used.has(slug); n += 1) { slug = `${base}-${String(n)}`; }
    used.add(slug);
    return { piece, slug, key: `${source.key}.${slug}` };
  });
  const whenOf = (piece: Piece) => fit(`Pick this for ${piece.names.join(', ')}.`, 200);
  const drafts = keyed.map(({ piece, slug, key }, index) => {
    const after = keyed[index + 1];
    return file(`${source.path}/${slug}.md`, {
      key,
      title: fit(`${source.title}: ${piece.title}`, 200),
      description: fit(`${source.title}, the part on ${piece.names.join(', ')}.`, 400),
      summary: fit(`${source.title}: ${piece.names.join(', ')}.`, SUMMARY_MAX),
      parent: qualified(source.key),
      ...(after === undefined ? {} : { next: qualified(after.key) }),
      fns: [...source.fns],
      ...(source.reference ? { suggest: 'none' as const, tags: ['authoring', 'reference'] } : { tags: ['authoring'] }),
    }, source.fns.length === 0 ? piece.text : `${piece.text.trim()}\n\n${fnsLine(source.fns)}`);
  });
  const list = keyed.map(({ piece, key }) => `- [${piece.title}](context:${qualified(key)})`);
  const body = [cut.head.trimEnd(), '', `This part is in ${String(keyed.length)} pieces; load the one you need:`, '', ...list].join('\n');
  return { body, choices: keyed.map(({ piece, key }) => ({ to: qualified(key), when: whenOf(piece) })), drafts };
}
