/**
 * The authoring guide in parts, one per topic, so a model with a small window reads only the parts it needs:
 * `guideParts` cuts the composed guide at its topic headings (with fs's own cutter, the one that serves them), and
 * `partsModule` writes the TypeScript fs declares its authoring context from (`systems/fs/shared/authoring.gen.ts`):
 * each part's context name, heading, title, size and whether it is reference only; the context declarations (dynamic,
 * each under the start item and naming the part after it, the reference parts never suggested); and `perPart`, which
 * keys one value per part by its context name, for the implementations.
 */
import { sectionOf } from '../../systems/fs/server/sections.ts';
import { topicHeading, type Topic } from './compose.ts';

/** About how many characters a token is, for the sizes the start item lists. */
const CHARS_PER_TOKEN = 4;

/** The system whose context the parts are. */
const SYSTEM = 'fs';

/** One part of the guide: its topic, its context name (`authoring-<topic>`), its heading and its text. */
export interface GuidePart {
  readonly topic: Topic;
  readonly name: string;
  readonly heading: string;
  readonly text: string;
}

/** The guide's parts in the outline's order. Throws when a topic's heading isn't in the guide. */
export function guideParts(guide: string, outline: readonly Topic[]): GuidePart[] {
  const headings = outline.map(topicHeading);
  return outline.map((topic, index) => {
    const heading = headings[index] ?? topicHeading(topic, index);
    const text = sectionOf(guide, heading, headings[index + 1]);
    if (text === undefined) { throw new Error(`the guide has no section "${heading}"`); }
    return { topic, name: `authoring-${topic.id}`, heading, text };
  });
}

/** A string as a single-quoted TypeScript literal. */
function quoted(text: string): string {
  return `'${text.replaceAll('\\', '\\\\').replaceAll('\'', '\\\'')}'`;
}

/** About how many tokens a text is, rounded to tens. */
function tokensOf(text: string): number {
  return Math.max(10, Math.round(text.length / CHARS_PER_TOKEN / 10) * 10);
}

/** The part a reader goes on to: the next one of the same kind (the guide's parts chain, then the reference parts). */
function nextOf(parts: readonly GuidePart[], index: number): GuidePart | undefined {
  const next = parts[index + 1];
  return next !== undefined && (next.topic.reference === true) === (parts[index]?.topic.reference === true) ? next : undefined;
}

/** The generated module's text. */
export function partsModule(parts: readonly GuidePart[]): string {
  const total = parts.length;
  const rows = parts.map((part, index) => {
    const next = nextOf(parts, index);
    const fields = [
      `heading: ${quoted(part.heading)}`, `title: ${quoted(part.topic.title)}`, `tokens: ${tokensOf(part.text)}`, `reference: ${part.topic.reference === true}`,
      ...(next === undefined ? [] : [`next: ${quoted(next.name)}`]),
    ];
    return `  ${quoted(part.name)}: { ${fields.join(', ')} },`;
  });
  const declarations = parts.map((part, index) => {
    const next = nextOf(parts, index);
    const kind = part.topic.reference === true ? 'reference part' : 'part';
    const description = `Writing a harness system, ${kind} ${index + 1} of ${total}: ${part.topic.title} (about ${tokensOf(part.text)} tokens).`;
    const fields = [
      `description: ${quoted(description)}`,
      'parent',
      ...(next === undefined ? [] : [`next: { ref: 'context', name: ${quoted(`${SYSTEM}/${next.name}`)} }`]),
      ...(part.topic.reference === true ? ["suggest: 'none'", "tags: ['reference']"] : []),
    ];
    return `    ${quoted(part.name)}: context({ ${fields.join(', ')} }),`;
  });
  return [
    '/**',
    ' * The parts of the system authoring guide (`packages/sdk/AUTHORING.md`), one per section, as fs offers them as',
    ' * context. Generated by `scripts/docs/authoring.ts` from the guide\'s outline (`npm run docs:authoring`); do not edit',
    ' * it by hand.',
    ' */',
    "import { context, type AnyContextRef } from '@harness/sdk';",
    '',
    '/**',
    ' * Each part by its context name: its section heading in the guide, its title, about how many tokens it is, whether',
    ' * it is reference only, and the part a reader goes on to.',
    ' */',
    'export const AUTHORING_PARTS = {',
    ...rows,
    '} as const;',
    '',
    '/** A part\'s context name. */',
    'export type AuthoringPart = keyof typeof AUTHORING_PARTS;',
    '',
    '/** The parts as dynamic context, each under `parent` (the start item) and naming the part after it; the reference parts are never suggested. */',
    'export function authoringContext(parent: AnyContextRef) {',
    '  return {',
    ...declarations,
    '  };',
    '}',
    '',
    '/** One value per part, keyed by its context name. */',
    'export function perPart<T>(make: (part: AuthoringPart) => T) {',
    '  return {',
    ...parts.map((part) => `    ${quoted(part.name)}: make(${quoted(part.name)}),`),
    '  };',
    '}',
    '',
  ].join('\n');
}
