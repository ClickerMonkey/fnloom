/**
 * Writes `.env.example` from the schemas: every hub tunable (`HUB_SETTINGS`) and the ones only `npm run dev` reads
 * (`devEnv`), each with its description and default, through `@ayepi/env`'s `envExample`. With `--check` it fails
 * when the file is stale instead of writing it, so a new or changed tunable breaks `npm run check` until the example
 * matches. The harness's own variables are cleared first, so defaults derived from others (the data paths, the URL)
 * come out the same on every machine.
 *
 * Run: npm run env:example   (check: npm run env:example -- --check)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { envExample, mergeEnvs } from '@ayepi/env';
import { HUB_SETTINGS } from '@harness/hub';
import { devEnv } from './dev-env.ts';

for (const key of Object.keys(process.env)) {
  if (key.startsWith('HARNESS_')) { Reflect.deleteProperty(process.env, key); }
}

const HEADER = [
  '# Generated by scripts/env-example.ts from the settings schemas. Do not edit; run `npm run env:example`.',
  '# Copy to .env (git-ignored) and fill in. `npm run dev` and the hub read it; values already in the environment win.',
  '# Durations are milliseconds.',
  '',
  '',
].join('\n');

const target = fileURLToPath(new URL('../.env.example', import.meta.url));
const text = HEADER + envExample(mergeEnvs(HUB_SETTINGS, devEnv).describe());

const check = process.argv.includes('--check');
const read = (): string => { try { return readFileSync(target, 'utf8'); } catch { return ''; } };
const current = read();
if (check) {
  if (current !== text) {
    console.error('env.example.stale', { file: target, fix: 'npm run env:example' });
    process.exit(1);
  }
} else if (current !== text) {
  writeFileSync(target, text);
  console.info('env.example.written', { file: target });
}
